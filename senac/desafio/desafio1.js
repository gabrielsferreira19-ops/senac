let prioridade = Number(prompt("digite a prioridade:"));


switch (prioridade) {
    case 1:console.log("urgente");
        
        break;

    case 2:console.log("alta");
        
        break;

    case 3:console.log("normal");
        
        break;

    case 4:console.log("baixa");
        
        break;

    default: console.log("prioridade invalida");
        break;
}